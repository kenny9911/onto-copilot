// 「内联 JS 一行都没被改写」的证据。
//
// 抽模块这件事本身没有对照物 —— 三千五百行搬来搬去，靠肉眼是查不出「某个条件被
// 手滑改了方向」的。所以这里做一次**逐行归并**：把原件（git blob 里那份内联 JS）
// 的每一行做归一化，再到 ts/src/ui/*.ts 里找同样的归一化结果。找不到的必须出现在
// 下面的 EXPECTED 名单里，且每一条都写清楚为什么。
//
// 归一化抹掉的只有「TS 化必然带来的形变」：
//   export 前缀 / G. 前缀 / `: any` 注解 / 单参箭头补的括号 / 非空断言 ! / 空白
// 判断方向、字符串字面量、正则、数字全都原样参与比对 —— 那些才是行为。
//
// ## React 化之后这条检查还剩什么价值
//
// 视图层改写成组件之后，那些行**不可能**再逐字找得到 —— 一个模板字符串变成一棵
// JSX 树，形状全变了。所以每迁走一个模块，被它替换掉的原始行要登记进
// REACT_REPLACED（和 EXPECTED 一样：一行一条，写清楚被哪个组件取代）。
//
// 这不是把检查关掉，是**把「换掉了多少」变成一个看得见的数**：还没迁的模块继续
// 享受逐行对照，迁走的部分留下一份账。哪天有人「顺手」改了一句还没迁的逻辑，
// 这里照样会响。
//
// 用法：node ts/tools/verify-ui-port.mjs

