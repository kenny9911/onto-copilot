/** ts/src/ui 下所有会发到浏览器的源码。**要递归、要认 .tsx** —— React 组件住在
 *  ts/src/ui/react/ 子目录里，只扫顶层 .ts 的话它们等于不存在。
 *  **.d.ts 要排除**：声明文件里一行运行时代码都没有，混进来只会给某条原始行
 *  凑出一个假的「找到了」，把真正的漏检盖掉。 */
function sources(dir) {
  const out = [];
  for (const f of readdirSync(dir)) {
    const p = resolve(dir, f);
    if (statSync(p).isDirectory()) { out.push(...sources(p)); continue; }
    if (f.endsWith(".d.ts")) continue;
    if (f.endsWith(".ts") || f.endsWith(".tsx")) out.push(p);
  }
  return out;
}

const ported = new Set();
for (const p of sources(resolve(ROOT, "ts/src/ui"))) {
  for (const line of readFileSync(p, "utf8").split("\n")) ported.add(norm(line));
}

const missing = [];
for (const line of originalJs) {
  const n = norm(line);
  if (!n || ported.has(n) || EXPECTED.has(n) || REACT_REPLACED.has(n)) continue;
  missing.push(line);
}

