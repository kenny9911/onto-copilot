function norm(s) {
  return s
    .replace(/^\s*export\s+/, "")
    .replace(/\bG\./g, "")
    .replace(/\(\s*([A-Za-z_$][\w$]*)\s*:\s*any\s*\)(\s*=>)/g, "$1$2")
    .replace(/:\s*any\[\]/g, "")
    .replace(/:\s*any\b/g, "")
    .replace(/!(?=[.;,)\]])/g, "")
    .replace(/\s+/g, "");
}

